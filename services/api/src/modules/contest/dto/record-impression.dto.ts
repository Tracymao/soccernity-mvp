import { Type } from 'class-transformer';
import { IsInt, IsNumber, IsUUID, Max, Min } from 'class-validator';
import { IMPRESSION_MIN_VISIBLE_MS, IMPRESSION_MIN_VISIBLE_RATIO } from '../contest-exposure.util';

// POST /contest/entries/:entryId/impression (B-092; Decision Log #405 item 7, #406 item 6).
//
// The client measures the viewport and sends the QUALIFYING event: the tile was at least 50% in
// view for one uninterrupted second. The server cannot observe the viewport, so it validates that
// the event CLAIMS at least that much; a claim below the threshold is a client bug and a 400. These
// two numbers are NOT stored (data minimisation): they are only checked.
export class RecordImpressionDto {
  // Generated by the client for this event. The idempotency key: replaying the same event (a retry,
  // a double-fired observer) for the same viewer and entry never counts twice.
  @IsUUID()
  eventId!: string;

  // Share of the tile in view, 0.5-1.
  @Type(() => Number)
  @IsNumber()
  @Min(IMPRESSION_MIN_VISIBLE_RATIO)
  @Max(1)
  visibleRatio!: number;

  // Uninterrupted milliseconds in view, at least 1000. The upper bound only stops an absurd value.
  @Type(() => Number)
  @IsInt()
  @Min(IMPRESSION_MIN_VISIBLE_MS)
  @Max(86_400_000)
  visibleMs!: number;
}
